"""Compare two ways of valuing players whose ratings are on the 1-10 scale, against the 20-80 value models as the reference.

Usage:
    PYTHONPATH=. python scripts/compare_scale_approaches.py Model-Sim                       # every stream, all ratings on 1-10
    PYTHONPATH=. python scripts/compare_scale_approaches.py Model-Sim --like Dugout26      # only Dugout26's 1-10 columns
    PYTHONPATH=. python scripts/compare_scale_approaches.py Model-Sim --streams batting --family ridge --holdout 3

For every model of the save, on the seasons the save has (the last `--holdout` seasons are the test seasons; training uses the
earlier ones, as when valuing a season not seen), three numbers, all against the real outcomes of the test rows:
  20-80   the model trained on 20-80 ratings, tested on the 20-80 ratings: the best a 20-80 league can do (the reference)
  A       the training ratings turned into 1-10 the way the game does it (model/scales.py), a model trained on those, tested
          on 1-10 ratings: "retrain on the coarse scale"
  B       the existing 20-80 model, tested on 1-10 ratings turned back into the 20-80 value expected for each: "convert and
          reuse"
The 1-10 ratings are made from the 20-80 ones of the training league with the conversion table of the game version
(config/rating-scales/<version>.csv, from scripts/build_scale_tables.py). Writes docs/rating-scale-comparison-<save>.md.
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from model import data, domains, registry, scales, splits
from model.metrics import summarize
from model.train import fit_table, make_model
from util import paths
from util.config import get_save
from util.seasons import available_seasons


def compare_spec(spec, save, seasons, conversion, columns, holdout, seed, family=None) -> dict:
    spec = registry.Spec(spec.name, spec.stream, spec.kind, family or spec.family, spec.position)
    plain = registry.build_table(spec, save, seasons)
    with data.ratings_view(scales.coarse_view(conversion, columns, back=False, seed=seed)):
        coarse = registry.build_table(spec, save, seasons)
    with data.ratings_view(scales.coarse_view(conversion, columns, back=True, seed=seed)):
        expected = registry.build_table(spec, save, seasons)
    same = all(t.frame[["ID", "season"]].equals(plain.frame[["ID", "season"]]) for t in (coarse, expected))
    if not same:
        raise RuntimeError(f"{spec.name}: the tables do not have the same rows")
    train, test = splits.last_seasons_holdout(plain.frame[plain.season].to_numpy(), holdout)
    test_rows = plain.frame.iloc[test]
    params = registry.model_params(spec, None)
    model_20 = fit_table(make_model(spec.family, **params), plain, train, seed)
    model_a = fit_table(make_model(spec.family, **params), coarse, train, seed)

    def score(prediction):
        return summarize(test_rows[plain.target], prediction, test_rows[plain.weight])

    return {
        "model": spec.name,
        "family": spec.family,
        "rows": len(test),
        "20-80": score(model_20.predict(plain.frame.iloc[test][plain.features])),
        "A": score(model_a.predict(coarse.frame.iloc[test][coarse.features])),
        "B": score(model_20.predict(expected.frame.iloc[test][expected.features])),
    }


def report(results: list[dict], save: str, version: str, like: str | None, holdout: int, columns) -> str:
    lines = [
        f"# 1-10 ratings: retrain (A) or convert and reuse (B) - {save}",
        "",
        f"Generated by `scripts/compare_scale_approaches.py`. Game version {version}; the last {holdout} seasons are the test "
        f"seasons, the models are trained on the seasons before them. Ratings turned to 1-10: "
        + (
            f"the columns that {like} shows as 1-10 ({len(columns)})."
            if like
            else f"all of the {len(columns)} model ratings."
        ),
        "",
        "- **20-80**: model trained and tested on 20-80 ratings (the reference).",
        "- **A**: model trained on the training ratings turned into 1-10, tested on 1-10 ratings.",
        "- **B**: the 20-80 model tested on 1-10 ratings turned back into the expected 20-80 value.",
        "",
        "Weighted R^2 against the real outcomes of the test rows (higher is better); loss = reference minus the approach.",
        "",
        "| model | family | test rows | 20-80 | A | B | loss A | loss B |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for r in results:
        base, a, b = r["20-80"]["r2"], r["A"]["r2"], r["B"]["r2"]
        lines.append(
            f"| {r['model']} | {r['family']} | {r['rows']} | {base:.3f} | {a:.3f} | {b:.3f} | {base - a:+.3f} | {base - b:+.3f} |"
        )
    base = np.array([r["20-80"]["r2"] for r in results])
    a = np.array([r["A"]["r2"] for r in results])
    b = np.array([r["B"]["r2"] for r in results])
    weights = np.array([r["rows"] for r in results], dtype=float)
    lines += [
        "",
        f"Average loss (by test rows): A {np.average(base - a, weights=weights):+.4f}, "
        f"B {np.average(base - b, weights=weights):+.4f}.",
        f"A is better than B in {int((a > b).sum())} of {len(results)} models.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Compare ways of valuing 1-10 ratings.")
    parser.add_argument("save", help="a training save with processed output (for example Model-Sim)")
    parser.add_argument("--like", help="a league with mixed scales: only the columns it shows as 1-10 are converted")
    parser.add_argument("--streams", nargs="+", choices=list(domains.REVIEWED_FEATURES), help="default: all")
    parser.add_argument("--family", help="use this model family for every model (faster than the chosen ones)")
    parser.add_argument("--start", type=int, help="first season (default: the first with data)")
    parser.add_argument("--holdout", type=int, default=5)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()

    config = get_save(args.save)
    version = scales.version_of(config.ratings)
    conversion = scales.Conversion.load(version)
    seasons = [s for s in available_seasons(args.save) if s >= (args.start or 0)]
    columns = scales.rating_columns()
    if args.like:
        latest = available_seasons(args.like)[-1]
        frame = pd.read_csv(paths.output_file(args.like, latest, "player-data"), low_memory=False)
        found = scales.detect_scales(frame)
        columns = [c for c in columns if found.get(c) == scales.S1_10]
        print(f"{args.like}: {len(columns)} of the model ratings are 1-10")
    results = []
    for spec in registry.specs(args.streams):
        result = compare_spec(spec, args.save, seasons, conversion, columns, args.holdout, args.seed, args.family)
        results.append(result)
        print(
            f"{result['model']:>20}: 20-80 {result['20-80']['r2']:.3f}  A {result['A']['r2']:.3f}  B {result['B']['r2']:.3f}"
        )
    out = args.out or Path(f"docs/rating-scale-comparison-{args.save}{'-' + args.like if args.like else ''}.md")
    out.write_text(report(results, args.save, version, args.like, args.holdout, columns))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
